from __future__ import annotations
import argparse
from collections import Counter
import json
from pathlib import Path
import re
import subprocess

TRAILER = re.compile(
    r"^Co-authored-by:\s+([^<>]+?)\s+<([^<>\s]+@[^<>\s]+)>$", re.IGNORECASE
)
AUTOGENERATED = {"pr-log.txt", "autobadge.py", "autobranch_pair.py"}


def git(path, *arguments):
    response = subprocess.run(
        ["git", "-C", str(path), *arguments],
        text=True,
        capture_output=True,
        timeout=30,
        check=False,
    )
    if response.returncode:
        raise ValueError(response.stderr.strip()[:400])
    return response.stdout


def inspect_commit(path, sha):
    output = git(path, "show", "-s", "--format=%H%x00%an%x00%ae%x00%aI%x00%B", sha)
    commit, name, email, timestamp, message = output.split("\x00", 4)
    authors, malformed = [], []
    blocks = message.strip().split("\n\n")
    trailer_block = blocks[-1].splitlines() if len(blocks) > 1 else []
    for line in message.splitlines():
        if not line.lower().startswith("co-authored-by:"):
            continue
        match = TRAILER.fullmatch(line.strip())
        if not match or line not in trailer_block:
            malformed.append(line)
        else:
            identity = {"name": match.group(1).strip(), "email": match.group(2).lower()}
            if identity not in authors:
                authors.append(identity)
    changes = []
    for line in git(
        path, "diff-tree", "--root", "--no-commit-id", "--numstat", "-r", sha
    ).splitlines():
        added, removed, filename = line.split("\t", 2)
        changes.append(
            {
                "path": filename,
                "added": None if added == "-" else int(added),
                "removed": None if removed == "-" else int(removed),
            }
        )
    substantive = [
        change for change in changes if Path(change["path"]).name not in AUTOGENERATED
    ]
    return {
        "sha": commit,
        "author": {"name": name, "email": email.lower()},
        "timestamp": timestamp,
        "subject": message.splitlines()[0] if message.strip() else "",
        "coAuthors": authors,
        "invalidTrailers": malformed,
        "changes": changes,
        "substantiveFiles": len(substantive),
    }


def audit(path, limit=200, ref="HEAD"):
    if not ref or ref.startswith("-") or len(ref) > 256:
        raise ValueError("invalid reference")
    if not 1 <= limit <= 10000:
        raise ValueError("limit must be 1..10000")
    git(path, "rev-parse", "--verify", ref + "^{commit}")
    commits = [
        inspect_commit(path, sha)
        for sha in git(
            path, "rev-list", "--max-count=" + str(limit), ref, "--"
        ).splitlines()
    ]
    names = Counter(
        author["email"] for commit in commits for author in commit["coAuthors"]
    )
    return {
        "repository": str(Path(path).resolve()),
        "ref": ref,
        "inspected": len(commits),
        "collaborativeCommits": sum(
            bool(c["coAuthors"]) and c["substantiveFiles"] > 0 for c in commits
        ),
        "malformedTrailers": sum(len(c["invalidTrailers"]) for c in commits),
        "coAuthorCounts": dict(sorted(names.items())),
        "commits": commits,
    }


def main():
    parser = argparse.ArgumentParser(
        description="Read-only audit of real Git collaboration"
    )
    parser.add_argument("repository", nargs="?", default=".")
    parser.add_argument("--limit", type=int, default=200)
    parser.add_argument("--ref", default="HEAD")
    args = parser.parse_args()
    print(json.dumps(audit(args.repository, args.limit, args.ref), indent=2))


if __name__ == "__main__":
    main()
